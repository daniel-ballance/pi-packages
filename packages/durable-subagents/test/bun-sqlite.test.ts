import test from 'node:test';
import assert from 'node:assert/strict';
import { BunSqliteDatabase } from '../src/bun-sqlite.js';

test('portable Bun SQL facade excludes concurrent operations and invalidates transaction handles', async () => {
  const builtin = 'Bun' in globalThis ? 'bun:sqlite' : 'node:sqlite';
  const module = await import(builtin);
  const native = new (module.Database ?? module.DatabaseSync)(':memory:');
  const database = new BunSqliteDatabase({ exec: sql => native.exec(sql), query: sql => { const statement = (native.query ?? native.prepare).call(native, sql); return { run: (...params: any[]) => statement.run(...params), get: (...params: any[]) => statement.get(...params) ?? null, all: (...params: any[]) => statement.all(...params) }; }, close: () => native.close() });
  await database.exec('CREATE TABLE items (value TEXT)');
  let release!: () => void;
  const barrier = new Promise<void>(resolve => { release = resolve; });
  let started!: () => void;
  const entered = new Promise<void>(resolve => { started = resolve; });
  let handle: Parameters<Parameters<typeof database.transaction>[0]>[0];
  const transaction = database.transaction(async tx => { handle = tx; await tx.run('INSERT INTO items VALUES (?)', 'rolled back'); started(); await barrier; throw new Error('rollback fixture'); });
  await entered;
  let outsideCompleted = false;
  const outside = database.run('INSERT INTO items VALUES (?)', 'outside').then(() => { outsideCompleted = true; });
  await new Promise(resolve => setImmediate(resolve));
  assert.equal(outsideCompleted, false);
  release();
  await assert.rejects(transaction, /rollback fixture/);
  await outside;
  assert.deepEqual((await database.all<{ value: string }>('SELECT value FROM items')).map(row => row.value), ['outside']);
  await assert.rejects(handle!.run('INSERT INTO items VALUES (?)', 'expired'), /no longer active/);
  await database.transaction(async tx => { await tx.run('INSERT INTO items VALUES (?)', 'committed'); });
  assert.equal((await database.all('SELECT value FROM items')).length, 2);
  let complete!: () => void;
  const pending = new Promise<void>(resolve => { complete = resolve; });
  let inside!: () => void;
  const active = new Promise<void>(resolve => { inside = resolve; });
  const held = database.transaction(async tx => { inside(); await pending; await tx.run('INSERT INTO items VALUES (?)', 'before close'); });
  await active;
  let closeCompleted = false;
  const closing = database.close().then(() => { closeCompleted = true; });
  await new Promise(resolve => setImmediate(resolve));
  assert.equal(closeCompleted, false);
  complete(); await held; await closing; await database.close();
  await assert.rejects(database.get('SELECT value FROM items'), /no longer active/);
});
